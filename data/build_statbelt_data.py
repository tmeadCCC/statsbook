"""Copy the textbook data sets into STATBELT Utility.

Run from the statsbook folder:  python3 data/build_statbelt_data.py ../statbelt/index.html

It reads data/catalog.json and the CSV files in data/, and replaces the block
between the TEXTBOOK-DATA markers in STATBELT's index.html. Run it again after
adding or correcting a data set, then publish both repositories.
"""
import csv, json, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent
cat = json.loads((here / "catalog.json").read_text(encoding="utf-8"))
sets = []
for c in cat:
    rows = list(csv.reader((here / f"{c['id']}.csv").open(encoding="utf-8")))
    sets.append({"id": c["id"], "t": c["title"], "s": c["sections"], "n": rows[0], "r": rows[1:]})

block = ("/* TEXTBOOK-DATA-START (generated by statsbook/data/build_statbelt_data.py; do not edit by hand) */\n"
         "const TBSETS=" + json.dumps(sets, ensure_ascii=False, separators=(",", ":")) + ";\n"
         "/* TEXTBOOK-DATA-END */")
target = pathlib.Path(sys.argv[1])
html = target.read_text(encoding="utf-8")
pat = re.compile(r"/\* TEXTBOOK-DATA-START.*?TEXTBOOK-DATA-END \*/", re.S)
if not pat.search(html):
    sys.exit("TEXTBOOK-DATA markers not found in " + str(target))
target.write_text(pat.sub(lambda m: block, html), encoding="utf-8")
print(f"Wrote {len(sets)} data sets into {target}")
